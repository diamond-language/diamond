#!/usr/bin/env bash
# Writes the header src/main.c includes for the suffix `d6 --version` adds to the release
# version, so a build from an interim git state says which one it is:
#
#   tools/version_suffix.sh VERSION OUTPUT
#
# The suffix is "-REVISION" (12 hex digits) when this source tree is a git checkout, plus
# "-dirty" when tracked files have uncommitted changes. A clean checkout of the release tag
# itself (vVERSION) gets no suffix, and neither does a tree without git (a source tarball).
# OUTPUT is only rewritten when its content changes, so an unchanged revision rebuilds nothing.
# Release artifacts (packages, portable tarballs) set D6_VERSION_SUFFIX, usually to nothing, to
# report exactly the version they are packaged as.
set -euo pipefail

version="${1:?usage: version_suffix.sh VERSION OUTPUT}"
output="${2:?usage: version_suffix.sh VERSION OUTPUT}"
repo="$(cd "$(dirname "$0")/.." && pwd -P)"

suffix=""
if [[ -n "${D6_VERSION_SUFFIX+set}" ]]; then
    suffix="$D6_VERSION_SUFFIX"
    [[ "$suffix" =~ ^[A-Za-z0-9.+-]*$ ]] || { echo "D6_VERSION_SUFFIX: letters, digits, . + - only" >&2; exit 64; }
# Only this tree's own repository counts, not one it happens to be vendored inside.
elif toplevel="$(git -C "$repo" rev-parse --show-toplevel 2>/dev/null)" &&
   [[ "$(cd "$toplevel" && pwd -P)" == "$repo" ]] &&
   revision="$(git -C "$repo" rev-parse --short=12 HEAD 2>/dev/null)"; then
    dirty=""
    if [[ -n "$(git -C "$repo" status --porcelain --untracked-files=no 2>/dev/null)" ]]; then
        dirty="-dirty"
    fi
    tag_commit="$(git -C "$repo" rev-parse -q --verify "refs/tags/v$version^{commit}" 2>/dev/null || true)"
    if [[ -n "$dirty" || "$tag_commit" != "$(git -C "$repo" rev-parse HEAD)" ]]; then
        suffix="-$revision$dirty"
    fi
fi

mkdir -p "$(dirname "$output")"
temporary="$(mktemp "$output.XXXXXX")"
printf '/* Generated by tools/version_suffix.sh; see there. */\n#define DIAMOND_VERSION_SUFFIX "%s"\n' \
    "$suffix" > "$temporary"
if cmp -s "$temporary" "$output"; then
    rm -f "$temporary"
else
    mv "$temporary" "$output"
fi
